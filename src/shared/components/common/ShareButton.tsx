export function ShareButton({
  title,
  url,
  description,
  size = "md",
  variant = "ghost",
}: ShareButtonProps) {
  const [copied, setCopied] = useState(false);
  const [open, setOpen] = useState(false);

  const fullUrl =
    typeof window !== "undefined"
      ? url.startsWith("http")
        ? url
        : `${window.location.origin}${url}`
      : url;

  const handleShare = (platform: (typeof platforms)[0]) => {
    if (platform.getUrl) {
      const shareUrl = platform.getUrl(fullUrl, title);
      window.open(shareUrl, "_blank", "width=600,height=400");
    } else {
      // Copy link for TikTok/Instagram
      handleCopyLink();
      toast.success(`คัดลอกลิงก์แล้ว - แปะใน ${platform.name} ได้เลย`);
    }
  };

  const handleCopyLink = async () => {
    try {
      await navigator.clipboard.writeText(fullUrl);
      setCopied(true);
      toast.success("คัดลอกลิงก์แล้ว");
      setTimeout(() => setCopied(false), 2000);
    } catch {
      toast.error("คัดลอกไม่สำเร็จ");
    }
  };

  const handleNativeShare = async () => {
    if (navigator.share) {
      try {
        await navigator.share({
          title,
          text: description || title,
          url: fullUrl,
        });
        setOpen(false);
      } catch {
        // User cancelled or error
      }
    }
  };

  const sizeClasses = {
    sm: "h-8 w-8",
    md: "h-9 w-9",
    lg: "h-10 w-10",
  };

  const iconSizes = {
    sm: "h-4 w-4",
    md: "h-5 w-5",
    lg: "h-5 w-5",
  };

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        <Button
          variant={variant}
          size="icon"
          className={sizeClasses[size]}
          aria-label="แชร์"
        >
          <Share2 className={iconSizes[size]} />
        </Button>
      </DialogTrigger>
      <DialogContent className="max-w-[320px] p-4 gap-3">
        <DialogHeader className="gap-1">
          <DialogTitle className="text-base">แชร์</DialogTitle>
          <DialogDescription className="line-clamp-1 text-xs">{title}</DialogDescription>
        </DialogHeader>

        {/* Social Icons Row */}
        <div className="flex justify-center gap-2">
          {platforms.map((platform) => {
            const Icon = platform.icon;
            return (
              <button
                key={platform.id}
                onClick={() => handleShare(platform)}
                className="w-8 h-8 rounded-full flex items-center justify-center hover:scale-110 transition-transform"
                style={{ backgroundColor: platform.color }}
                title={`แชร์ไปยัง ${platform.name}`}
              >
                <Icon className="w-4 h-4 text-white" />
              </button>
            );
          })}
        </div>

        {/* Copy Link Section */}
        <div className="flex items-center gap-2 p-2 bg-muted rounded-lg overflow-hidden">
          <p className="text-[11px] text-muted-foreground truncate flex-1 min-w-0">{fullUrl}</p>
          <Button
            variant="outline"
            size="sm"
            onClick={handleCopyLink}
            className="flex-shrink-0 h-6 text-xs px-2"
          >
            {copied ? (
              <Check className="h-3 w-3" />
            ) : (
              <Copy className="h-3 w-3" />
            )}
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}

